#!/bin/sh
# warp-gen.sh — register free Cloudflare WARP devices and write AmneziaWG configs.
# Usage: warp-gen.sh [count] [proxy]   (count default 1; proxy optional, e.g. http://192.168.0.12:9220)
#        docker compose exec amnezia-proxy /scripts/warp-gen.sh 10
#
# The proxy is used only for the registration: the Cloudflare API is blocked by some ISPs,
# so register through a tunnel that reaches it. The resulting configs work from anywhere.
# WARP_PROXY=... does the same as the second argument.
#
# Each config is a separate anonymous WARP registration with its own key pair; the
# private key is generated here and never leaves this machine. Cloudflare's end is
# plain WireGuard, so the AmneziaWG fields are the client-only ones: junk packets
# (Jc/Jmin/Jmax) and a QUIC-like signature packet (I1), with S1/S2 = 0 and H1-H4 = 1-4.
# The failover manager picks new files up from $WARP_OUT by itself.
#
#   WARP_OUT=/configs                  where the configs are written
#   WARP_ENDPOINT=162.159.192.7:4500   Cloudflare endpoint written into the configs
#   WARP_PAUSE=3                       seconds between registrations (rate limits)

OUT="${WARP_OUT:-/configs}"
ENDPOINT="${WARP_ENDPOINT:-162.159.192.7:4500}"
PAUSE="${WARP_PAUSE:-3}"
API="https://api.cloudflareclient.com/v0a2158/reg"
COUNT="${1:-1}"
PROXY="${2:-${WARP_PROXY:-}}"

die() { echo "error: $*" >&2; exit 1; }
case "$COUNT" in ''|*[!0-9]*|0) die "count must be a positive number" ;; esac
for c in awg curl jq; do command -v "$c" > /dev/null || die "$c is required"; done
mkdir -p "$OUT" || die "cannot create $OUT"

# QUIC Initial look-alike: long header, version 1, 20 random bytes of connection id, then random payload
make_i1() {
    local dcid
    dcid=$(od -An -N20 -tx1 /dev/urandom | tr -d ' \n')
    printf '<b 0xc200000001%s%s0000><r 1170>' "14" "$dcid"
}

made=0
i=1
while [ "$i" -le "$COUNT" ]; do
    priv=$(awg genkey)
    pub=$(printf '%s' "$priv" | awg pubkey)
    body=$(jq -nc --arg k "$pub" --arg t "$(date -u +%Y-%m-%dT%H:%M:%S.000Z)" \
        '{key:$k, install_id:"", fcm_token:"", tos:$t, type:"Android", model:"PC", locale:"en_US", warp_enabled:true}')
    resp=$(curl -fsS --max-time 20 ${PROXY:+--proxy "$PROXY"} -X POST "$API" \
        -H 'Content-Type: application/json' -H 'User-Agent: okhttp/3.12.1' -H 'CF-Client-Version: a-6.10-2158' \
        -d "$body" 2>&1) || { echo "registration $i/$COUNT failed: $resp" >&2; i=$((i + 1)); sleep "$PAUSE"; continue; }

    id=$(printf '%s' "$resp" | jq -r '.id // empty')
    peer=$(printf '%s' "$resp" | jq -r '.config.peers[0].public_key // empty')
    v4=$(printf '%s' "$resp" | jq -r '.config.interface.addresses.v4 // empty')
    v6=$(printf '%s' "$resp" | jq -r '.config.interface.addresses.v6 // empty')
    if [ -z "$id" ] || [ -z "$peer" ] || [ -z "$v4" ]; then
        echo "registration $i/$COUNT: unexpected answer from Cloudflare" >&2
        i=$((i + 1)); sleep "$PAUSE"; continue
    fi

    file="$OUT/warp-$(printf '%s' "$id" | cut -c1-8).conf"
    ( umask 077
      cat > "$file" <<CONF
# Cloudflare WARP (free), generated by warp-gen.sh on $(date -u +%Y-%m-%d)
[Interface]
PrivateKey = $priv
Address = $v4/32${v6:+, $v6/128}
DNS = 1.1.1.1, 1.0.0.1
MTU = 1280
S1 = 0
S2 = 0
Jc = 4
Jmin = 40
Jmax = 70
H1 = 1
H2 = 2
H3 = 3
H4 = 4
I1 = $(make_i1)

[Peer]
PublicKey = $peer
AllowedIPs = 0.0.0.0/0, ::/0
Endpoint = $ENDPOINT
PersistentKeepalive = 25
CONF
    )
    echo "created $file"
    made=$((made + 1))
    i=$((i + 1))
    [ "$i" -gt "$COUNT" ] || sleep "$PAUSE"
done
echo "done: $made of $COUNT configs written to $OUT"
[ "$made" -gt 0 ]
